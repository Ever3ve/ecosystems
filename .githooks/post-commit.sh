#!/bin/bash

# Масив із 10 анекдотів про програмістів
ANECDOTES=(
  "😂 Дружина відправляє чоловіка-програміста в магазин:\n   — Купи батон хліба, а якщо будуть яйця — візьми десяток.\n   Програміст приходить у магазин:\n   — У вас є яйця?\n   — Так.\n   — Тоді дайте 10 батонів хліба!"
  
  "😂 Існує 10 типів людей: ті, хто розуміють двійкову систему числення, і ті, хто ні."
  
  "😂 Молодший розробник: 'У мене все працює на моєму комп'ютері!'\n   Senior: 'Чудово, тоді викачуємо твій комп'ютер на продакшн!'"
  
  "😂 Навіщо програмісти носять окуляри?\n   Щоб краще бачити C# (C-sharp)!"
  
  "😂 Стоять три розробники біля зламаного авто. Бізнес-аналітик: 'Давайте перевіримо інструкцію'. Тестувальник: 'Давайте поштовхаємо'. Програміст: 'А давайте вийдемо з машини та зайдемо знову?'"
  
  "😂 Скільки програмістів потрібно, щоб змінити лампочку?\n   Жодного, це проблема на боці апаратного забезпечення (hardware issue)."
  
  "😂 Алгоритм — це слово, яке використовують програмісти, коли не хочуть пояснювати, як саме працює їхній код."
  
  "😂 Життя розробника: fix bugs -> push -> trigger new bugs -> repeat."
  
  "😂 Код працює з першої спроби?\n   Підозріло... Десь явно ховається супер-баг!"
  
  "😂 Сидить розробник за компом, до нього підходить син:\n   — Тату, а чому сонце щоранку сходить на сході, а заходить на заході?\n   — Сину, це дійсно так працює?\n   — Так.\n   — Щодня?\n   — Так.\n   — Тоді благаю, нічого не чіпай і не рефактор!"
)

# Вибір випадкового анекдоту
RANDOM_INDEX=$((RANDOM % ${#ANECDOTES[@]}))
SELECTED_ANECDOTE="${ANECDOTES[$RANDOM_INDEX]}"

# Вивід у консоль
echo -e "\n----------------------------------------"
echo -e "🎉 Коміт успішно створено! Не забудь зробити push."
echo -e "----------------------------------------"
echo -e "$SELECTED_ANECDOTE"
echo -e "----------------------------------------\n"

# Запис дати та анекдоту у лог-файл
clean_msg=$(echo -e "$SELECTED_ANECDOTE" | tr '\n' ' ')
echo "$(date '+%Y-%m-%d %H:%M:%S') - $clean_msg" >> .git/commit_history.log